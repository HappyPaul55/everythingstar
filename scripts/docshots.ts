/**
 * Turn every capture fence in `docs/` into a Playwright spec, write the manifest
 * the page reads, then take the pictures.
 *
 * Run by `bun run build` before Astro. It is deliberate that this never renders a
 * page: the spec is the document's own test, verbatim, and the only thing added
 * is the `docshot()` registration.
 *
 * `--only <doc>` is for the authoring loop: generate and run one document while
 * the rest of the manifest, whose images already exist, is left alone.
 */
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import docshots from "../docshots.config";
import { clearContentCache } from "../src/lib/docshots/cache";
import { fenceShots, type FenceShot } from "../src/lib/docshots/fence";
import {
  MANIFEST_PATH,
  shotKey,
  variantFile,
  writeManifest,
  type Manifest,
  type Shot,
} from "../src/lib/docshots/manifest";

const ROOT = process.cwd();
const DOCS = join(ROOT, "docs");
const SPECS = join(ROOT, ".docshots", "specs");

const only = (() => {
  const index = process.argv.indexOf("--only");
  return index === -1 ? null : (process.argv[index + 1] ?? null);
})();

function docs(): { id: string; path: string }[] {
  return readdirSync(DOCS, { recursive: true, encoding: "utf8" })
    .map((file) => file.replace(/\\/g, "/"))
    .filter((file) => file.endsWith(".md"))
    .map((file) => ({ id: file.slice(0, -".md".length), path: join(DOCS, file) }))
    .sort((a, b) => a.id.localeCompare(b.id));
}

const problems: string[] = [];
const shots: Shot[] = [];
const fences: FenceShot[] = [];
const seen = new Map<string, string>();

for (const doc of docs()) {
  const { shots: found, problems: foundProblems } = fenceShots(
    readFileSync(doc.path, "utf8"),
    doc.id,
  );
  problems.push(...foundProblems);

  for (const fence of found) {
    const previous = seen.get(fence.id);
    if (previous) {
      problems.push(
        `${fence.doc}:${fence.line}: id "${fence.id}" is already used by ${previous}; ids name a file`,
      );
    }
    seen.set(fence.id, fence.doc);
    fences.push(fence);

    const names = fence.viewports ?? Object.keys(docshots.variants);
    for (const name of names) {
      if (!docshots.variants[name]) {
        problems.push(
          `${fence.doc}:${fence.line}: "${name}" is not a variant in docshots.config.ts`,
        );
      }
    }
    for (const name of Object.keys(fence.crop ?? {})) {
      if (!names.includes(name)) {
        problems.push(
          `${fence.doc}:${fence.line}: crop names "${name}", which this capture does not take`,
        );
      }
    }

    shots.push({
      doc: fence.doc,
      id: fence.id,
      alt: fence.alt,
      ...(fence.caption ? { caption: fence.caption } : {}),
      ...(fence.crop ? { crop: fence.crop } : {}),
      variants: names
        .filter((name) => docshots.variants[name])
        .map((name) => ({
          name,
          file: variantFile(fence.id, name),
          ...docshots.variants[name]!.viewport,
        })),
    });
  }
}

if (problems.length > 0) {
  console.error("docshots: the capture fences have problems\n");
  for (const problem of problems) console.error(`  ${problem}`);
  console.error("\nNothing was generated.");
  process.exit(1);
}

/**
 * The manifest of an `--only` run keeps the documents it did not visit, as long
 * as their images are still on disk; otherwise the next build would lose them.
 */
const previous: Manifest | null = existsSync(join(ROOT, MANIFEST_PATH))
  ? (JSON.parse(readFileSync(join(ROOT, MANIFEST_PATH), "utf8")) as Manifest)
  : null;

const selected = only === null ? null : new Set(shots.filter((s) => s.doc === only).map((s) => s.doc));
const kept: Record<string, Shot> = {};
if (previous && only !== null) {
  for (const [key, shot] of Object.entries(previous.shots)) {
    if (selected?.has(shot.doc)) continue;
    if (shot.variants.every((variant) => existsSync(join(ROOT, previous.outDir, variant.file)))) {
      kept[key] = shot;
    }
  }
}

const manifest: Manifest = {
  version: 1,
  outDir: docshots.outDir,
  quality: docshots.quality,
  shots: {
    ...kept,
    ...Object.fromEntries(
      shots
        .filter((shot) => only === null || shot.doc === only)
        .map((shot) => [shotKey(shot.doc, shot.id), shot]),
    ),
  },
};

rmSync(SPECS, { recursive: true, force: true });
mkdirSync(SPECS, { recursive: true });

// One stable import for every fence: the generated tree is the only place that
// knows where the repository's own fixture lives.
writeFileSync(
  join(SPECS, "support.ts"),
  [
    "// Generated by `bun run docs:shots`. Do not edit.",
    'export { expect, test } from "@playwright/test";',
    'export * from "../../tests/e2e/fixture";',
    'export * from "../../tests/e2e/docs-library";',
    'export * from "../../tests/e2e/docs-screens";',
    'export * from "../../tests/e2e/note-guide";',
    'export * from "../../tests/e2e/helpers";',
    "",
  ].join("\n"),
);

function specOf(fence: FenceShot): string {
  const guard =
    fence.viewports && fence.viewports.length > 0
      ? [
          "test.beforeEach(({}, testInfo) => {",
          `  if (!${JSON.stringify(fence.viewports)}.includes(testInfo.project.name)) testInfo.skip();`,
          "});",
          "",
        ].join("\n")
      : "";

  return [
    `// Generated from docs/${fence.doc}.md:${fence.line} by \`bun run docs:shots\`.`,
    'import { docshot } from "../../src/lib/docshots/capture";',
    "",
    `docshot(test, { doc: ${JSON.stringify(fence.doc)}, id: ${JSON.stringify(fence.id)} });`,
    "",
    guard + fence.body,
    "",
  ].join("\n");
}

for (const fence of fences) {
  if (only !== null && fence.doc !== only) continue;
  const file = `${fence.doc.replace(/\//g, "-")}--${fence.id}.spec.ts`;
  writeFileSync(join(SPECS, file), specOf(fence));
}

writeManifest(ROOT, manifest);

const count = Object.keys(manifest.shots).length;
console.log(
  `docshots: ${count} capture(s) across ${new Set(shots.map((shot) => shot.doc)).size} document(s) → ${relative(ROOT, SPECS)}`,
);
console.log(`docshots: images → ${docshots.outDir}/ (${Object.keys(docshots.variants).join(", ")})`);

// The content layer caches every page it compiled, including one compiled before
// its captures existed. Start from empty on both sides of the run.
clearContentCache();

// The browser runs from here rather than from a second package script, so
// `bun run docs:shots --only <doc>` hands its flag to the generator instead of
// to Playwright.
execFileSync("bunx", ["playwright", "test", "--config", "playwright.docs.config.ts"], {
  cwd: ROOT,
  stdio: "inherit",
});

// A green capture run that wrote nothing is the failure that hides: the build
// would render a placeholder, and only `check:docs` would notice. Say it here,
// where the missing file is the answer.
const missing = Object.entries(manifest.shots).flatMap(([key, shot]) =>
  shot.variants
    .map((variant) => join(ROOT, manifest.outDir, variant.file))
    .filter((file) => !existsSync(file))
    .map((file) => `${key} → ${relative(ROOT, file)}`),
);
if (missing.length > 0) {
  console.error("docshots: the capture run passed but wrote no image for:");
  for (const entry of missing) console.error(`  ${entry}`);
  process.exit(1);
}
console.log(`docshots: ${count} image(s) ready in ${docshots.outDir}/`);
